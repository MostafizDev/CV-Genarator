#!/usr/bin/env bash
# Sets up (first run) and starts a local Postgres for development, using the PostgreSQL
# binaries already on your PATH (e.g. `brew install postgresql@14`).
#
# It creates TWO roles, which is what makes Row Level Security meaningful:
#   cvgen_owner  owns the tables, runs migrations (bypasses RLS)   -> MIGRATION_DATABASE_URL
#   cvgen_app    what the API connects as; RLS applies to it       -> DATABASE_URL
# and writes generated passwords and keys into backend/.env (gitignored). Nothing secret
# is stored in Git.
#
# Usage: scripts/dev_db.sh [start|stop|status]
set -euo pipefail

BACKEND_DIR="$(cd "$(dirname "$0")/.." && pwd)"
DATA_DIR="$BACKEND_DIR/.pgdata"
ENV_FILE="$BACKEND_DIR/.env"
PORT="${CVGEN_PG_PORT:-54329}"
DB_NAME="cvgen"

action="${1:-start}"

case "$action" in
  stop)   pg_ctl -D "$DATA_DIR" stop; exit 0 ;;
  status) pg_ctl -D "$DATA_DIR" status; exit 0 ;;
  start)  ;;
  *) echo "usage: $0 [start|stop|status]"; exit 1 ;;
esac

rand() { python3 -c "import secrets;print(secrets.token_hex(16))"; }

if [ ! -d "$DATA_DIR" ]; then
  if [ -f "$ENV_FILE" ] && grep -q '^DATABASE_URL=' "$ENV_FILE"; then
    echo "backend/.env already defines DATABASE_URL but there is no local cluster at $DATA_DIR."
    echo "Remove those lines (or the file) first, so fresh credentials can be generated."; exit 1
  fi

  OWNER_PW="$(rand)"; APP_PW="$(rand)"
  echo "Initialising Postgres cluster in $DATA_DIR ..."
  PWFILE="$(mktemp)"; trap 'rm -f "$PWFILE"' EXIT; printf '%s' "$OWNER_PW" > "$PWFILE"
  initdb -D "$DATA_DIR" -U cvgen_owner --auth=scram-sha-256 --pwfile="$PWFILE" -E UTF8 >/dev/null
  rm -f "$PWFILE"

  pg_ctl -D "$DATA_DIR" -l "$DATA_DIR/server.log" -o "-p $PORT -c listen_addresses=127.0.0.1" -w start >/dev/null
  export PGPASSWORD="$OWNER_PW"
  psql -h 127.0.0.1 -p "$PORT" -U cvgen_owner -d postgres -v ON_ERROR_STOP=1 -q <<SQL
CREATE ROLE cvgen_app LOGIN PASSWORD '$APP_PW' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
CREATE DATABASE $DB_NAME OWNER cvgen_owner;
REVOKE ALL ON DATABASE $DB_NAME FROM PUBLIC;
GRANT CONNECT ON DATABASE $DB_NAME TO cvgen_app;
SQL

  KEY="key1:$(python3 -c "import os,base64;print(base64.urlsafe_b64encode(os.urandom(32)).decode())")"
  touch "$ENV_FILE"; chmod 600 "$ENV_FILE"
  {
    echo ""
    echo "# --- generated by scripts/dev_db.sh (gitignored; never commit) ---"
    echo "DATABASE_URL=postgresql://cvgen_app:$APP_PW@127.0.0.1:$PORT/$DB_NAME"
    echo "MIGRATION_DATABASE_URL=postgresql://cvgen_owner:$OWNER_PW@127.0.0.1:$PORT/$DB_NAME"
    grep -q '^DATA_ENCRYPTION_KEYS=' "$ENV_FILE" || echo "DATA_ENCRYPTION_KEYS=$KEY"
    grep -q '^JWT_SECRET=' "$ENV_FILE" || echo "JWT_SECRET=$(python3 -c "import secrets;print(secrets.token_urlsafe(48))")"
  } >> "$ENV_FILE"
  echo "Created roles cvgen_owner / cvgen_app and wrote credentials to backend/.env"
else
  pg_ctl -D "$DATA_DIR" status >/dev/null 2>&1 || \
    pg_ctl -D "$DATA_DIR" -l "$DATA_DIR/server.log" -o "-p $PORT -c listen_addresses=127.0.0.1" -w start >/dev/null
fi
echo "Postgres is running on 127.0.0.1:$PORT (database: $DB_NAME)"
